def addr32(w, h, bw):
    """CT32 픽셀(x,y)의 바이트 주소 배열 [h,w]"""
    y, x = np.mgrid[0:h, 0:w]
    page = (y // 32) * bw + (x // 64)
    block = np.array(BLOCK32)[(y // 8) % 4, (x // 8) % 8]
    word = np.array(COL32)[y % 8, x % 8]
    return ((page * 32 + block) * 64 + word) * 4


def addr8(w, h, bw):
    y, x = np.mgrid[0:h, 0:w]
    page = (y // 64) * (bw // 2) + (x // 128)
    block = np.array(BLOCK8)[(y // 16) % 4, (x // 16) % 8]
    byte = np.array(COL8)[y % 16, x % 16]
    return (page * 32 + block) * 256 + byte


def ct32_to_t8(data, w32, h32, w8, h8):
    """CT32 (w32 x h32) 로 업로드된 바이트열 → PSMT8 (w8 x h8) 인덱스 [h8,w8]"""
    mem = np.zeros(max(len(data), w8 * h8) * 2, np.uint8)
    a = addr32(w32, h32, max(1, w32 // 64))
    src = np.frombuffer(data, np.uint8).reshape(h32, w32, 4)
    for k in range(4):
        mem[a + k] = src[:, :, k]
    return mem[addr8(w8, h8, max(1, w8 // 64))]


def t8_to_ct32(idx, w32, h32, w8, h8):
    mem = np.zeros(w8 * h8 * 2, np.uint8)
    mem[addr8(w8, h8, max(1, w8 // 64))] = idx
    a = addr32(w32, h32, max(1, w32 // 64))
    out = np.zeros((h32, w32, 4), np.uint8)
    for k in range(4):
        out[:, :, k] = mem[a + k]
    return out.tobytes()


