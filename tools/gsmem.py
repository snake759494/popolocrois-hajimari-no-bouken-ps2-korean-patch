def addr4(w, h, bw, base_nib=0):
    """PSMT4 픽셀의 니블 주소"""
    y, x = np.mgrid[0:h, 0:w]
    page = (y // 128) * (bw // 2) + (x // 128)
    block = np.array(BLOCK4)[(y // 16) % 8, (x // 32) % 4]
    nib = np.array(COL4)[y % 16, x % 32]
    return base_nib + (page * 32 + block) * 512 + nib


def mem_from_ct32(data, w32, h32, size=None):
    mem = np.zeros(size or len(data), np.uint8)
    a = addr32(w32, h32, max(1, w32 // 64))
    src = np.frombuffer(data, np.uint8).reshape(h32, w32, 4)
    for k in range(4):
        mem[a + k] = src[:, :, k]
    return mem


def read4(mem, w, h, bw, base_nib=0):
    a = addr4(w, h, bw, base_nib)
    b = mem[a >> 1]
    return np.where(a & 1, b >> 4, b & 15)
